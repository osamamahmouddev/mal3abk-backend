namespace Malabak.Api.Infrastructure.Media;

/// <summary>Object storage for media variants. Local disk in development; an S3/Azure Blob adapter plugs in with the hosting ADR.</summary>
public interface IObjectStorage
{
    Task PutAsync(string key, byte[] content, string contentType, CancellationToken cancellationToken = default);

    Task<byte[]?> GetAsync(string key, CancellationToken cancellationToken = default);
}

/// <summary>
/// Stores files under a private directory (never wwwroot) — they're only reachable through the media endpoint,
/// which applies visibility rules. Keys are generated by us, but are still validated against path traversal.
/// </summary>
public sealed class LocalObjectStorage : IObjectStorage
{
    private readonly string _root;

    public LocalObjectStorage(IConfiguration configuration, IHostEnvironment environment)
    {
        _root = Path.GetFullPath(configuration["Media:LocalRoot"] ?? Path.Combine(environment.ContentRootPath, "App_Data", "media"));
        Directory.CreateDirectory(_root);
    }

    public async Task PutAsync(string key, byte[] content, string contentType, CancellationToken cancellationToken = default)
    {
        var path = Resolve(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await File.WriteAllBytesAsync(path, content, cancellationToken);
    }

    public async Task<byte[]?> GetAsync(string key, CancellationToken cancellationToken = default)
    {
        var path = Resolve(key);
        return File.Exists(path) ? await File.ReadAllBytesAsync(path, cancellationToken) : null;
    }

    private string Resolve(string key)
    {
        var path = Path.GetFullPath(Path.Combine(_root, key));
        if (!path.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
        {
            throw new InvalidOperationException("Invalid storage key.");
        }

        return path;
    }
}

/// <summary>Antivirus hook. Re-encoding already discards non-image payloads; a ClamAV/cloud scanner can be wired here.</summary>
public interface IMalwareScanner
{
    Task<bool> IsCleanAsync(byte[] content, CancellationToken cancellationToken = default);
}

public sealed class NoOpMalwareScanner : IMalwareScanner
{
    public Task<bool> IsCleanAsync(byte[] content, CancellationToken cancellationToken = default) => Task.FromResult(true);
}
